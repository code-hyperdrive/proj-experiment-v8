export interface UserRow {
  id: string;
  custom_id: string | null;
  display_name: string | null;
  is_anonymous: number;
  sign_in_provider: string;
  email: string | null;
  provider_user_id: string | null;
  avatar_url: string | null;
  created_at: number;
  last_sync_at: number | null;
  last_active_date: string | null;
  preferences_json: string;
  genre_stats_json: string;
  country_stats_json: string;
  total_listening_time: number;
}

export function rowToProfile(row: UserRow) {
  return {
    id: row.id,
    customId: row.custom_id,
    displayName: row.display_name,
    isAnonymous: !!row.is_anonymous,
    signInProvider: row.sign_in_provider,
    email: row.email,
    avatarUrl: row.avatar_url,
    createdAt: row.created_at,
    lastSyncAt: row.last_sync_at,
    preferences: JSON.parse(row.preferences_json || '{}'),
    genreStats: JSON.parse(row.genre_stats_json || '{}'),
    countryStats: JSON.parse(row.country_stats_json || '{}'),
    totalListeningTime: row.total_listening_time,
  };
}

export async function getUser(db: D1Database, uid: string): Promise<UserRow | null> {
  return db.prepare('SELECT * FROM users WHERE id = ?').bind(uid).first<UserRow>();
}

/**
 * Creates a brand-new anonymous user + its first session in one atomic
 * batch — this is the only place a `users` row gets created (see
 * routes/auth.ts's POST /anonymous). `userId` is generated by the caller
 * (crypto.randomUUID()) rather than derived from anything client-supplied.
 */
export async function createAnonymousUserWithSession(
  db: D1Database,
  opts: { userId: string; tokenHash: string; now: number; expiresAt: number }
): Promise<void> {
  const today = new Date(opts.now).toISOString().split('T')[0];
  await db.batch([
    db
      .prepare(
        `INSERT INTO users (id, is_anonymous, sign_in_provider, created_at, last_sync_at, last_active_date)
         VALUES (?, 1, 'anonymous', ?, ?, ?)`
      )
      .bind(opts.userId, opts.now, opts.now, today),
    db
      .prepare(
        'INSERT INTO sessions (token_hash, user_id, created_at, last_seen_at, expires_at) VALUES (?, ?, ?, ?, ?)'
      )
      .bind(opts.tokenHash, opts.userId, opts.now, opts.now, opts.expiresAt),
  ]);
}

/** Creates a session for a user that already exists (Google sign-in — the user row was found/linked/created separately). */
export async function createSessionForUser(
  db: D1Database,
  opts: { userId: string; tokenHash: string; now: number; expiresAt: number }
): Promise<void> {
  await db
    .prepare('INSERT INTO sessions (token_hash, user_id, created_at, last_seen_at, expires_at) VALUES (?, ?, ?, ?, ?)')
    .bind(opts.tokenHash, opts.userId, opts.now, opts.now, opts.expiresAt)
    .run();
}

export async function findUserByProvider(
  db: D1Database,
  provider: string,
  providerUserId: string
): Promise<UserRow | null> {
  return db
    .prepare('SELECT * FROM users WHERE sign_in_provider = ? AND provider_user_id = ?')
    .bind(provider, providerUserId)
    .first<UserRow>();
}

export interface ProviderIdentity {
  provider: string;
  providerUserId: string;
  email: string | null;
  displayName: string | null;
  // Optional (not required) so existing call sites/tests that predate
  // Google avatar support don't all need updating — omitted means "no
  // picture claim," same as an explicit null.
  avatarUrl?: string | null;
}

/**
 * Converts an existing anonymous user's row IN PLACE into a
 * provider-linked one — same `id`, so every favorites/history row
 * (foreign-keyed to that same id) stays attached with zero data
 * migration, mirroring what Firebase Auth's account linking gave us for
 * free before this backend dropped Firebase entirely. `COALESCE` on
 * display_name so a name the user already set locally isn't clobbered by
 * whatever (possibly empty) name the provider returned.
 */
export async function linkAnonymousUserToProvider(
  db: D1Database,
  anonymousUserId: string,
  identity: ProviderIdentity
): Promise<UserRow> {
  await db
    .prepare(
      `UPDATE users
       SET sign_in_provider = ?, provider_user_id = ?, email = ?, avatar_url = ?, is_anonymous = 0,
           display_name = COALESCE(display_name, ?), last_sync_at = ?
       WHERE id = ?`
    )
    .bind(
      identity.provider,
      identity.providerUserId,
      identity.email,
      identity.avatarUrl ?? null,
      identity.displayName,
      Date.now(),
      anonymousUserId
    )
    .run();
  return (await getUser(db, anonymousUserId))!;
}

export async function createProviderUser(db: D1Database, identity: ProviderIdentity): Promise<UserRow> {
  const userId = crypto.randomUUID();
  const now = Date.now();
  const today = new Date(now).toISOString().split('T')[0];
  await db
    .prepare(
      `INSERT INTO users (id, is_anonymous, sign_in_provider, provider_user_id, email, display_name, avatar_url, created_at, last_sync_at, last_active_date)
       VALUES (?, 0, ?, ?, ?, ?, ?, ?, ?, ?)`
    )
    .bind(
      userId,
      identity.provider,
      identity.providerUserId,
      identity.email,
      identity.displayName,
      identity.avatarUrl ?? null,
      now,
      now,
      today
    )
    .run();
  return (await getUser(db, userId))!;
}

/**
 * The find-or-link-or-create orchestrator for a provider sign-in
 * (currently just Google, but generic over `provider`).
 *
 * - An existing account for this exact provider identity always wins —
 *   returned as-is, `anonymousUserId` is ignored (we don't merge INTO an
 *   already-established account from an unrelated anonymous session;
 *   that's a real merge-conflict problem, not an "upgrade," and wasn't
 *   asked for).
 * - Otherwise, if there's a currently-anonymous account to upgrade,
 *   convert it in place (see linkAnonymousUserToProvider).
 * - Otherwise, create a brand-new account.
 *
 * The race-fallback below (re-checking for an existing provider match
 * after a failed link/create) handles two callback requests for the same
 * Google identity landing concurrently — the UNIQUE index on
 * (sign_in_provider, provider_user_id) would otherwise surface as a raw
 * constraint error instead of just returning the row the other request
 * already created.
 */
export async function findOrCreateProviderUser(
  db: D1Database,
  identity: ProviderIdentity,
  anonymousUserId: string | null
): Promise<{ user: UserRow; wasLinked: boolean; isNewUser: boolean }> {
  const existing = await findUserByProvider(db, identity.provider, identity.providerUserId);
  if (existing) {
    // Google's profile picture can change over time (or arrive null on a
    // token that omitted the scope) — keep it fresh on every repeat
    // sign-in rather than only ever setting it once at creation/link time.
    const newAvatarUrl = identity.avatarUrl ?? null;
    if (newAvatarUrl !== existing.avatar_url) {
      await db.prepare('UPDATE users SET avatar_url = ? WHERE id = ?').bind(newAvatarUrl, existing.id).run();
      existing.avatar_url = newAvatarUrl;
    }
    return { user: existing, wasLinked: false, isNewUser: false };
  }

  if (anonymousUserId) {
    const anonUser = await getUser(db, anonymousUserId);
    if (anonUser && anonUser.is_anonymous) {
      try {
        const linked = await linkAnonymousUserToProvider(db, anonymousUserId, identity);
        return { user: linked, wasLinked: true, isNewUser: false };
      } catch (err) {
        const raced = await findUserByProvider(db, identity.provider, identity.providerUserId);
        if (raced) return { user: raced, wasLinked: false, isNewUser: false };
        throw err;
      }
    }
  }

  try {
    const created = await createProviderUser(db, identity);
    return { user: created, wasLinked: false, isNewUser: true };
  } catch (err) {
    const raced = await findUserByProvider(db, identity.provider, identity.providerUserId);
    if (raced) return { user: raced, wasLinked: false, isNewUser: false };
    throw err;
  }
}

export async function findSessionByTokenHash(
  db: D1Database,
  tokenHash: string
): Promise<{ userId: string; expiresAt: number } | null> {
  const row = await db
    .prepare('SELECT user_id, expires_at FROM sessions WHERE token_hash = ?')
    .bind(tokenHash)
    .first<{ user_id: string; expires_at: number }>();
  if (!row) return null;
  return { userId: row.user_id, expiresAt: row.expires_at };
}

/** Sliding-window renewal — called on every successfully authenticated request (see lib/auth.ts). */
export async function touchSession(db: D1Database, tokenHash: string, newExpiresAt: number): Promise<void> {
  await db
    .prepare('UPDATE sessions SET last_seen_at = ?, expires_at = ? WHERE token_hash = ?')
    .bind(Date.now(), newExpiresAt, tokenHash)
    .run();
}

export async function deleteSession(db: D1Database, tokenHash: string): Promise<void> {
  await db.prepare('DELETE FROM sessions WHERE token_hash = ?').bind(tokenHash).run();
}

export async function updateProfile(
  db: D1Database,
  uid: string,
  patch: { displayName?: string; customId?: string; preferences?: Record<string, unknown> }
): Promise<void> {
  const existing = await db
    .prepare('SELECT preferences_json FROM users WHERE id = ?')
    .bind(uid)
    .first<{ preferences_json: string }>();
  if (!existing) {
    throw new NotFoundError('Profile not found — call GET /api/v1/profile first');
  }

  const sets: string[] = [];
  const values: unknown[] = [];

  if (patch.displayName !== undefined) {
    sets.push('display_name = ?');
    values.push(patch.displayName);
  }
  if (patch.customId !== undefined) {
    sets.push('custom_id = ?');
    values.push(patch.customId);
  }
  if (patch.preferences !== undefined) {
    const merged = { ...JSON.parse(existing.preferences_json || '{}'), ...patch.preferences };
    sets.push('preferences_json = ?');
    values.push(JSON.stringify(merged));
  }
  if (sets.length === 0) return;

  sets.push('last_sync_at = ?');
  values.push(Date.now());

  try {
    await db
      .prepare(`UPDATE users SET ${sets.join(', ')} WHERE id = ?`)
      .bind(...values, uid)
      .run();
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    if (message.toUpperCase().includes('UNIQUE')) {
      throw new ConflictError('That custom ID is already taken');
    }
    throw err;
  }
}

export async function deleteUser(db: D1Database, uid: string): Promise<void> {
  // Explicit deletes rather than relying solely on the schema's ON DELETE
  // CASCADE — correct either way, but doesn't depend on D1's foreign-key
  // enforcement being on.
  await db.batch([
    db.prepare('DELETE FROM sessions WHERE user_id = ?').bind(uid),
    db.prepare('DELETE FROM favorites WHERE user_id = ?').bind(uid),
    db.prepare('DELETE FROM history WHERE user_id = ?').bind(uid),
    db.prepare('DELETE FROM users WHERE id = ?').bind(uid),
  ]);
}

export async function listFavorites(
  db: D1Database,
  uid: string
): Promise<{ stationId: string; addedAt: number }[]> {
  const { results } = await db
    .prepare('SELECT station_id, created_at FROM favorites WHERE user_id = ? ORDER BY position ASC')
    .bind(uid)
    .all<{ station_id: string; created_at: number }>();
  return results.map((r) => ({ stationId: r.station_id, addedAt: r.created_at }));
}

export async function addFavorite(
  db: D1Database,
  uid: string,
  stationId: string
): Promise<{ added: boolean; alreadyExists: boolean }> {
  const existing = await db
    .prepare('SELECT 1 FROM favorites WHERE user_id = ? AND station_id = ?')
    .bind(uid, stationId)
    .first();
  if (existing) {
    return { added: false, alreadyExists: true };
  }

  const countRow = await db
    .prepare('SELECT COUNT(*) as c FROM favorites WHERE user_id = ?')
    .bind(uid)
    .first<{ c: number }>();
  if ((countRow?.c ?? 0) >= MAX_FAVORITES) {
    throw new LimitExceededError(`Favorites limit reached (${MAX_FAVORITES})`);
  }

  const maxPosRow = await db
    .prepare('SELECT COALESCE(MAX(position), -1) as maxPos FROM favorites WHERE user_id = ?')
    .bind(uid)
    .first<{ maxPos: number }>();
  const position = (maxPosRow?.maxPos ?? -1) + 1;

  await db
    .prepare('INSERT INTO favorites (user_id, station_id, position, created_at) VALUES (?, ?, ?, ?)')
    .bind(uid, stationId, position, Date.now())
    .run();

  return { added: true, alreadyExists: false };
}

export async function removeFavorite(db: D1Database, uid: string, stationId: string): Promise<void> {
  await db.prepare('DELETE FROM favorites WHERE user_id = ? AND station_id = ?').bind(uid, stationId).run();
}

export async function reorderFavorites(db: D1Database, uid: string, order: string[]): Promise<void> {
  const { results } = await db
    .prepare('SELECT station_id FROM favorites WHERE user_id = ?')
    .bind(uid)
    .all<{ station_id: string }>();
  const currentSet = new Set(results.map((r) => r.station_id));
  const orderSet = new Set(order);

  if (currentSet.size !== orderSet.size || [...currentSet].some((id) => !orderSet.has(id))) {
    throw new ValidationError('order must contain exactly the current set of favorite stationIds, each once');
  }

  const stmts = order.map((stationId, index) =>
    db.prepare('UPDATE favorites SET position = ? WHERE user_id = ? AND station_id = ?').bind(index, uid, stationId)
  );
  await db.batch(stmts);
}

export async function addHistoryEntry(db: D1Database, uid: string, entry: HistoryEntryInput): Promise<void> {
  const now = Date.now();

  // Fetch (and existence-check) the user row FIRST, before writing
  // anything — history.user_id has a foreign key against users(id), so
  // inserting for a uid with no profile would otherwise fail with a raw
  // D1_ERROR/FOREIGN KEY constraint failure instead of this clean,
  // caller-facing NotFoundError (caught by a real test case; this
  // ordering is load-bearing, not stylistic).
  const userRow = await db
    .prepare('SELECT genre_stats_json, country_stats_json, total_listening_time FROM users WHERE id = ?')
    .bind(uid)
    .first<{ genre_stats_json: string; country_stats_json: string; total_listening_time: number }>();
  if (!userRow) {
    throw new NotFoundError('Profile not found — call GET /api/v1/profile first');
  }

  await db
    .prepare(
      'INSERT INTO history (user_id, station_id, genre, country, played_at, duration_seconds) VALUES (?, ?, ?, ?, ?, ?)'
    )
    .bind(uid, entry.stationId, entry.genre ?? null, entry.country ?? null, now, entry.durationSeconds)
    .run();

  // Trim to the most-recent MAX_HISTORY entries for this user. Keyed on
  // `rowid` (unique per row), not `played_at` — an earlier version
  // filtered by played_at value, which under a tie (two entries sharing
  // the exact same millisecond timestamp — plausible under real traffic)
  // could retain MORE than MAX_HISTORY rows, since `NOT IN (values)`
  // keeps *every* row matching a surviving value, not just one. Caught by
  // a real test seeding a timestamp collision, not a hypothetical.
  await db
    .prepare(
      `DELETE FROM history WHERE user_id = ? AND rowid NOT IN (
         SELECT rowid FROM history WHERE user_id = ? ORDER BY played_at DESC, rowid DESC LIMIT ?
       )`
    )
    .bind(uid, uid, MAX_HISTORY)
    .run();

  const genreStats: Record<string, number> = JSON.parse(userRow.genre_stats_json || '{}');
  const countryStats: Record<string, number> = JSON.parse(userRow.country_stats_json || '{}');
  if (entry.genre) genreStats[entry.genre] = (genreStats[entry.genre] ?? 0) + 1;
  if (entry.country) countryStats[entry.country] = (countryStats[entry.country] ?? 0) + 1;
  const newTotal = (userRow.total_listening_time ?? 0) + entry.durationSeconds;

  await db
    .prepare(
      'UPDATE users SET genre_stats_json = ?, country_stats_json = ?, total_listening_time = ?, last_sync_at = ? WHERE id = ?'
    )
    .bind(JSON.stringify(genreStats), JSON.stringify(countryStats), newTotal, now, uid)
    .run();
}

export async function listHistory(
  db: D1Database,
  uid: string
): Promise<{ stationId: string; genre: string | null; country: string | null; playedAt: number; durationSeconds: number }[]> {
  const { results } = await db
    .prepare(
      'SELECT station_id, genre, country, played_at, duration_seconds FROM history WHERE user_id = ? ORDER BY played_at DESC'
    )
    .bind(uid)
    .all<{ station_id: string; genre: string | null; country: string | null; played_at: number; duration_seconds: number }>();
  return results.map((r) => ({
    stationId: r.station_id,
    genre: r.genre,
    country: r.country,
    playedAt: r.played_at,
    durationSeconds: r.duration_seconds,
  }));
}

export interface GlobalStats {
  connectedUsers: number;
  activeUsers: number;
  lastUpdated: number;
}

export async function getGlobalStats(db: D1Database): Promise<GlobalStats> {
  const row = await db
    .prepare('SELECT connected_users, active_users, last_updated FROM stats_global WHERE id = 1')
    .first<{ connected_users: number; active_users: number; last_updated: number }>();
  return {
    connectedUsers: row?.connected_users ?? 0,
    activeUsers: row?.active_users ?? 0,
    lastUpdated: row?.last_updated ?? 0,
  };
}

/**
 * Mirrors the delta/decay logic that used to live in js/firebase-sync.js's
 * recordUserActivity/updateGlobalStats: activeUsers decays ~2%/hour of
 * inactivity (capped at 24h) before a delta is applied. This is a
 * best-effort display counter, not a security boundary — a plain
 * sequential read-then-write (rather than a D1 transaction) leaves a tiny
 * race window under concurrent requests, an accepted tradeoff at this
 * app's traffic scale, same as the Firestore version's tolerance before it.
 */
async function applyGlobalStatsDelta(
  db: D1Database,
  connectedDelta: number,
  activeDelta: number
): Promise<GlobalStats> {
  const statsRow = await db
    .prepare('SELECT connected_users, active_users, last_updated FROM stats_global WHERE id = 1')
    .first<{ connected_users: number; active_users: number; last_updated: number }>();

  const now = Date.now();
  let activeUsers = statsRow?.active_users ?? 0;
  const connectedUsers = statsRow?.connected_users ?? 0;
  const lastUpdated = statsRow?.last_updated ?? 0;

  const hoursSinceUpdate = lastUpdated ? (now - lastUpdated) / (1000 * 60 * 60) : 0;
  if (hoursSinceUpdate > 1) {
    const decayFactor = Math.pow(0.98, Math.min(hoursSinceUpdate, 24));
    activeUsers = Math.floor(activeUsers * decayFactor);
  }

  const newConnected = Math.max(0, connectedUsers + connectedDelta);
  const newActive = Math.max(0, activeUsers + activeDelta);

  await db
    .prepare('UPDATE stats_global SET connected_users = ?, active_users = ?, last_updated = ? WHERE id = 1')
    .bind(newConnected, newActive, now)
    .run();

  return { connectedUsers: newConnected, activeUsers: newActive, lastUpdated: now };
}

/** Called once, at account creation (routes/auth.ts's POST /anonymous) — a genuinely new user, always +1/+1. */
export async function recordNewUserStats(db: D1Database): Promise<GlobalStats> {
  return applyGlobalStatsDelta(db, 1, 1);
}

/** Called on every GET /profile — +1 active the first time a user is seen on a given UTC day, no change otherwise. */
export async function recordDailyActivityAndGetStats(db: D1Database, uid: string): Promise<GlobalStats> {
  const today = new Date().toISOString().split('T')[0];
  const userRow = await db
    .prepare('SELECT last_active_date FROM users WHERE id = ?')
    .bind(uid)
    .first<{ last_active_date: string | null }>();
  const lastActiveDate = userRow?.last_active_date ?? null;

  if (lastActiveDate === today) {
    return getGlobalStats(db);
  }

  await db.prepare('UPDATE users SET last_active_date = ? WHERE id = ?').bind(today, uid).run();
  return applyGlobalStatsDelta(db, 0, 1);
}
